const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.KAOYAN_CHROME,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:900},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.resolve(__dirname,'../app/src/main/assets/index.html'));
 await page.getByRole('heading',{name:'今天，也向前一步'}).waitFor();
 await page.screenshot({path:path.resolve(__dirname,'../test-results/home-tablet.png'),fullPage:true});
 await page.locator('[data-action="nav"][data-view="notes"]').first().click();
 await page.locator('[data-action="edit-record"]').first().click();
 await page.locator('#record-title').fill('极限 <script>window.pwned=true</script>');
 await page.locator('#record-body').fill('等价无穷小替换需要满足替换条件；不要直接替换加减中的部分。');
 await page.locator('#record-subject').selectOption('数学');
 await page.locator('#record-manual').check();
 await page.locator('[data-action="save-record"]').click();
 await page.locator('.note').filter({hasText:'极限'}).waitFor();
 assert.equal(await page.evaluate(()=>window.pwned),undefined);
 await page.reload();
 await page.getByRole('heading',{name:'今天，也向前一步'}).waitFor();
 await page.locator('[data-action="nav"][data-view="notes"]').first().click();
 assert.equal(await page.locator('.note').count(),1);
 await page.locator('[data-action="nav"][data-view="ask"]').first().click();
 await page.locator('#question').fill('无穷小');
 await page.locator('[data-action="search"]').click();
 assert.equal(await page.locator('.reference').count(),1);
 await page.locator('.reference').click();
 await page.locator('.content-text').filter({hasText:'替换条件'}).waitFor();
 await page.locator('[data-action="close-modal"]').click();
 await page.locator('[data-action="nav"][data-view="home"]').first().click();
 await page.locator('[data-action="toggle-task"]').first().click();
 assert.equal(await page.locator('.task.done').count(),1);
 await page.reload();await page.getByRole('heading',{name:'今天，也向前一步'}).waitFor();
 assert.equal(await page.locator('.task.done').count(),1);
 await page.locator('[data-action="nav"][data-view="english"]').first().click();
 await page.screenshot({path:path.resolve(__dirname,'../test-results/english-tablet.png'),fullPage:true});
 await page.locator('[data-action="nav"][data-view="settings"]').first().click();
 await page.screenshot({path:path.resolve(__dirname,'../test-results/settings-tablet.png'),fullPage:true});
 assert.equal(await page.locator('#api-key').getAttribute('type'),'password');
 await page.setViewportSize({width:412,height:915});
 await page.locator('.mobile-nav [data-view="home"]').click();
 await page.screenshot({path:path.resolve(__dirname,'../test-results/home-phone.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('UI checks passed: note persistence, escaped text, retrieval citation, task persistence, password field, responsive layout; no browser errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
